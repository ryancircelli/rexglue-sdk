bool ParseUint(const char* text, uint64_t& out) {
  if (!text || !*text) {
    return false;
  }
  char* end = nullptr;
  unsigned long long value = std::strtoull(text, &end, 0);
  if (end == text) {
    return false;
  }
  out = value;
  return true;
}

